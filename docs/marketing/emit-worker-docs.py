#!/usr/bin/env python3
"""Bundle the built one-pagers into the catspotters.com worker.

The documents are deliberately NOT placed in the worker's public/ directory:
static assets there are served before the worker runs, which would hand
anybody the gated pages at a guessable URL. Compiling them into the worker
means the only way to reach them is through the gate.
"""
import json, pathlib

here = pathlib.Path(__file__).parent
out = here.parent.parent / 'artifacts' / 'coming-soon' / 'src' / 'documents.js'

PAGES = {
    'media': 'media.html',
    'forpurpose': 'charities.html',
    'boundless': 'boundless-life.html',
}
SKELETON = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            '<meta name="robots" content="noindex,nofollow">{body}</html>')

def page(fname):
    raw = (here / fname).read_text()
    return SKELETON.format(body=f'<head-end>{raw}').replace('<head-end>', '</head><body>') + '</body>'

docs = {slug: page(f) for slug, f in PAGES.items()}
gate = page('gate.html')

admin = here.parent.parent / 'artifacts' / 'admin' / 'src' / 'pages.js'
admin.write_text(
    '// GENERATED by docs/marketing/emit-worker-docs.py - do not edit.\n'
    '// Rebuild with: cd docs/marketing && sh build.sh\n'
    f'export const WORKSPACE_PAGE = {json.dumps(page("workspace.html"), ensure_ascii=False)};\n'
    f'export const SIGNIN_PAGE = {json.dumps(page("signin.html"), ensure_ascii=False)};\n'
)
print(f'wrote {admin.relative_to(here.parent.parent)} ({admin.stat().st_size // 1024} KB)')

out.write_text(
    '// GENERATED by docs/marketing/emit-worker-docs.py — do not edit.\n'
    '// Rebuild with: cd docs/marketing && sh build.sh\n'
    f'export const DOCUMENTS = {json.dumps(docs, ensure_ascii=False)};\n'
    f'export const GATE_PAGE = {json.dumps(gate, ensure_ascii=False)};\n'
)
print(f'wrote {out.relative_to(here.parent.parent)} '
      f'({out.stat().st_size // 1024} KB, {len(docs)} documents + gate)')
